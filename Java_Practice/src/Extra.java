public class Extra {
    static void main() {
        int score = 80;

        if (score >= 90) {
            System.out.print("A");
        }


        if (score >= 80) {
            System.out.print("B");
        }

        if (score >= 70) {
            System.out.print("C");
        }

        if (score >= 60) {
            System.out.print("D");
        } else {
            System.out.print("E");
        }
    }
}
